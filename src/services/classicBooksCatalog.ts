/**
 * Busca livros no catálogo clássico e popular local com alta tolerância e inteligência de nomes
 */
export function searchLocalClassics(query: string): SearchResultBook[] {
  const norm = query
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();

  if (!norm) return [];

  const cleanIsbn = query.replace(/[-\s]/g, '');

  // Variações e pseudônimos literários comuns
  const isJulesVerneQuery =
    (norm.includes('verne') && (norm.includes('jules') || norm.includes('julio'))) ||
    norm === 'verne' ||
    norm === 'jules' ||
    norm === 'jules verne' ||
    norm === 'julio verne';

  const isOrwellQuery = norm.includes('orwell');

  const isMachadoAuthorQuery =
    norm.includes('machado') || norm.includes('assis');

  return CLASSIC_BOOKS_CATALOG.filter((book) => {
    if (cleanIsbn && (book.isbn13 === cleanIsbn || book.isbn10 === cleanIsbn)) {
      return true;
    }

    const normTitle = book.titulo
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');

    const normSubtitle = (book.subtitulo || '')
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');

    const normAuthors = book.autores
      .join(' ')
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');

    const normPublisher = (book.editora || '')
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');

    // 1. Atalhos para autores muito consultados
    if (isJulesVerneQuery && (normAuthors.includes('verne') || normAuthors.includes('jules'))) {
      return true;
    }
    if (isOrwellQuery && (normAuthors.includes('orwell') || normTitle.includes('1984'))) {
      return true;
    }
    if (isMachadoAuthorQuery && normAuthors.includes('machado')) {
      return true;
    }

    // 2. Busca exata ou por substring no título, subtítulo ou autor
    if (normTitle.includes(norm)) return true;
    if (normSubtitle.includes(norm)) return true;
    if (normAuthors.includes(norm)) return true;
    if (normPublisher.includes(norm)) return true;

    // 3. Busca por palavras individuais (todas as palavras presentes em título + autor)
    const words = norm.split(/\s+/).filter(Boolean);
    if (words.length > 1) {
      const matchAll = words.every(
        (w) => normTitle.includes(w) || normAuthors.includes(w) || normSubtitle.includes(w)
      );
      if (matchAll) return true;
    }

    // 4. Se qualquer palavra com 4 ou mais letras for o sobrenome do autor
    for (const w of words) {
      if (w.length >= 4 && normAuthors.includes(w)) {
        return true;
      }
    }

    return false;
  });
}
